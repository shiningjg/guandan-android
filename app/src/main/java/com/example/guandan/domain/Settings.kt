package com.example.guandan.domain

/**
 * AI 出牌速度档位。
 *
 * [delayMs] 为电脑每次行动前的「思考」等待时间，仅影响观感节奏，不影响 AI 的决策内容。
 * 调速在设置里即时生效（下一次出牌就按新档位等待），并通过 SharedPreferences 记住偏好。
 */
enum class AiSpeed(val label: String, val delayMs: Long) {
    FAST("快", 250L),
    NORMAL("中", 650L),
    SLOW("慢", 1200L),
}

/**
 * 升级方式（可在「⚙ 设置 → 升级方式」里切换，切换后自动重开一场）。
 *
 * - [SHARED] **共用级数**（单机简化、本 APP 原有行为）：全场只有一条级数，
 *   不论哪队赢都往上加，钳制到 A；打 A 时头游且队友不是末游即夺冠。
 * - [PER_TEAM] **各自记级**（国家体育总局《竞技掼蛋竞赛规则》标准）：
 *   两队各自从 2 记级，**只有上游方可以升级**；每副牌打的级牌取
 *   「上一副上游方所升到的级数」；胜负最终以双方级数高低（最高为「过 A」）判定。
 *   只有**自己级数已到 A** 的那一方，在打自己 A 的那副拿到头游且搭档不是末游，才算过 A 夺冠。
 *
 * 依据：掼蛋国际竞赛标准第二条（定义十「升级」、定义十一「级数」）、第十三条（记级）、
 * 第十四条（胜负判定）；2022《竞技掼蛋竞赛规则（试行）》术语「级牌牌点与上副牌
 * 上游所升至级数相同的牌为级牌」。
 */
enum class LevelMode {
    SHARED,
    PER_TEAM,
}
